const pick = (a, rnd) => a[Math.floor(rnd() * a.length)]
// склеиваем начало и окончание; три одинаковые гласные подряд и двойные мягкие знаки сглаживаем
const glue = (a, b) => (a + b).replace(/([аеёиоуыэюя])\1+/gi, '$1').replace(/ьь/g, 'ь').replace(/^./, c => c.toUpperCase())

export const NAME_RACES = Object.keys(N)

// одно имя; race — ключ из RACES, gender — 'm' | 'f' (по умолчанию случайно)
export function makeName(race, gender, rnd = Math.random) {
  const r = N[race] || N.human
  const g = gender === 'm' || gender === 'f' ? gender : rnd() < 0.5 ? 'm' : 'f'
  const [heads, tails] = r[g]
  const name = glue(pick(heads, rnd), pick(tails, rnd))
  if (r.fam) { // у людей — фамилия с родом
    const f = pick(r.fam, rnd)
    const fam = /(ов|ев|ин)$/.test(f) ? f : f + 'ов'
    return `${name} ${g === 'f' ? fam + 'а' : fam}`
  }
  if (r.clan) return `${pick(r.clan, rnd)} ${name}`
  if (r.house) return `${name} из дома ${pick(r.house, rnd)}`
  if (r.tag && rnd() < 0.45) { const [tm, tf] = pick(r.tag, rnd).split('/'); return `${name} ${g === 'f' ? tf || tm : tm}` }
  return name
}

// раса по населению поселения: чем больше жителей, тем чаще выпадает
export function raceFromPeople(races, rnd = Math.random) {
  const list = (races || []).map(r => ({ race: r.race, n: (r.male || 0) + (r.female || 0) + (r.kids || 0) || 1 }))
  if (!list.length) return 'human'
  let x = rnd() * list.reduce((s, r) => s + r.n, 0)
  for (const r of list) if ((x -= r.n) < 0) return r.race
  return list[list.length - 1].race
}
