const HEX = /^#[0-9a-f]{6}$/i
const num = (v, lo, hi, d) => { const n = Number(v); return Number.isFinite(n) ? Math.min(hi, Math.max(lo, n)) : d }
const pick = (v, list, d) => (list.some(x => x.k === v) ? v : d)

// проверка вида: всё лишнее отбрасывается, плохое заменяется обычным
export function cleanLook(raw) {
  if (!raw || typeof raw !== 'object') return null
  const hex = (v, d) => (HEX.test(String(v || '')) ? String(v).toLowerCase() : d)
  return {
    m: pick(raw.m, MATERIALS, 'leather'),
    c: hex(raw.c, '#4a3526'),
    f: hex(raw.f, '#d9b25c'),
    h: Math.round(num(raw.h, 0, 1, 0.6) * 100) / 100,
    w: Math.round(num(raw.w, 0, 1, 0.5) * 100) / 100,
    wear: Math.round(num(raw.wear, 0, 3, 1)),
    bands: Math.round(num(raw.bands, 0, 5, 3)),
    title: pick(raw.title, TITLES, 'foil'),
    em: pick(raw.em, EMBLEMS, ''),
    deco: [...new Set((Array.isArray(raw.deco) ? raw.deco : []).filter(k => DECOS.some(d => d.k === k)))].slice(0, 8),
    rib: hex(raw.rib, '#8e1a14'),
    glow: hex(raw.glow, ''),
    desc: String(raw.desc || '').replace(/\r/g, '').slice(0, 1500)
  }
}

