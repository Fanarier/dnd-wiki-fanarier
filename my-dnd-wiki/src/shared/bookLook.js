function hash(str) { let h = 2166136261; for (const ch of String(str)) { h ^= ch.codePointAt(0); h = Math.imul(h, 16777619) } return h >>> 0 }
export function defaultLook(s) {
  const h = hash(s.id || s.name || 'x')
  const r = n => ((h >>> n) & 255) / 255
  const cls = `${s.cls || ''} ${s.sub || ''}`
  const em = CLASS_EMBLEM.find(([re]) => re.test(cls))?.[1] || ''
  const acc = HEX.test(s.accent || '') ? s.accent.toLowerCase() : ''
  return {
    m: r(3) > 0.8 ? 'cloth' : 'leather',
    c: COVER_COLORS[h % 11],
    f: '#d9b25c',
    h: 0.45 + r(8) * 0.5, w: 0.25 + r(16) * 0.5,
    wear: 1 + (h % 2), bands: 2 + (h % 3), title: 'foil', em,
    deco: acc ? ['ribbon'] : [], rib: acc || '#8e1a14', glow: '', desc: ''
  }
}
// вид книги: у героев Анкарии — нарисованный вручную (со своей живой деталью), у остальных — по классу и id
export function lookOf(s) {
  const p = PRESETS[String(s.name || '').trim().toLowerCase()]
  return p ? { ...cleanLook(p), fx: p.fx || '' } : cleanLook(defaultLook(s))
}
